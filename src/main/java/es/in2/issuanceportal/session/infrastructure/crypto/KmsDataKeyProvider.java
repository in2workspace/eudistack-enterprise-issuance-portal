package es.in2.issuanceportal.session.infrastructure.crypto;

import com.github.benmanes.caffeine.cache.Cache;
import com.github.benmanes.caffeine.cache.Caffeine;
import es.in2.issuanceportal.shared.error.ProblemCode;
import es.in2.issuanceportal.shared.error.ProblemException;
import software.amazon.awssdk.core.SdkBytes;
import software.amazon.awssdk.core.exception.SdkException;
import software.amazon.awssdk.services.kms.KmsClient;
import software.amazon.awssdk.services.kms.model.DataKeySpec;
import software.amazon.awssdk.services.kms.model.GenerateDataKeyResponse;

import java.nio.ByteBuffer;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.concurrent.atomic.AtomicReference;
import java.util.function.Supplier;

/**
 * Data keys generated by the environment's KMS key. A data key is reused until it is older than the
 * rotation period; unwrapped keys are cached so decrypting a session does not call KMS every time.
 * Any KMS failure is a 503: nothing is ever stored or returned in clear because of it.
 */
public class KmsDataKeyProvider implements DataKeyProvider {

    private final KmsClient kms;
    private final String keyId;
    private final Duration rotation;
    private final Clock clock;
    private final Cache<ByteBuffer, byte[]> unwrapped;

    /** The key and when it was created, swapped together so no thread reads one without the other. */
    private record Generation(DataKey key, Instant createdAt) {
    }

    private final AtomicReference<Generation> current = new AtomicReference<>();

    public KmsDataKeyProvider(KmsClient kms, String keyId, Duration rotation, Clock clock) {
        if (keyId == null || keyId.isBlank()) {
            throw new IllegalArgumentException("A KMS key id is required");
        }
        this.kms = kms;
        this.keyId = keyId;
        this.rotation = rotation;
        this.clock = clock;
        // A key unwrapped once stays valid for the sessions it encrypted, which live at most 15 minutes
        // past the rotation that retired it.
        this.unwrapped = Caffeine.newBuilder()
                .expireAfterAccess(rotation.plusHours(1))
                .maximumSize(100)
                .build();
    }

    @Override
    public DataKey currentKey() {
        Instant now = clock.instant();
        Generation generation = current.get();
        if (isStale(generation, now)) {
            // One KMS call per rotation, however many requests arrive at once.
            synchronized (this) {
                generation = current.get();
                if (isStale(generation, now)) {
                    generation = new Generation(generate(), now);
                    current.set(generation);
                }
            }
        }
        return generation.key();
    }

    private boolean isStale(Generation generation, Instant now) {
        return generation == null || !now.isBefore(generation.createdAt().plus(rotation));
    }

    @Override
    public byte[] unwrap(byte[] wrapped) {
        return unwrapped.get(ByteBuffer.wrap(wrapped.clone()), key -> callKms(() -> kms.decrypt(request -> request
                .keyId(keyId)
                .ciphertextBlob(SdkBytes.fromByteArray(wrapped))).plaintext().asByteArray()));
    }

    private DataKey generate() {
        GenerateDataKeyResponse response = callKms(() -> kms.generateDataKey(request -> request
                .keyId(keyId)
                .keySpec(DataKeySpec.AES_256)));
        byte[] plaintext = response.plaintext().asByteArray();
        byte[] wrapped = response.ciphertextBlob().asByteArray();
        unwrapped.put(ByteBuffer.wrap(wrapped.clone()), plaintext);
        return new DataKey(plaintext, wrapped);
    }

    private static <T> T callKms(Supplier<T> call) {
        try {
            return call.get();
        } catch (SdkException e) {
            throw new ProblemException(ProblemCode.SERVICE_UNAVAILABLE, e);
        }
    }
}
